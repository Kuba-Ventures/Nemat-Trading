import re, sys
root = sys.argv[1]
s = open(f"{root}/thank-you-insert-options.html").read()

def card(i):
    depth = 0
    for m in re.finditer(r'<(/?)div\b', s[i:]):
        depth += -1 if m.group(1) else 1
        if depth == 0:
            e = i + m.end()
            return s[i:e + s[e:].find('>') + 1]

starts = [m.start() for m in re.finditer(r'<div style="width:312px;height:437px', s)]
front, back = card(starts[0]), card(starts[1])
defs = re.search(r'<svg width="0" height="0" style="position:absolute">\s*<defs>.*?</defs>\s*</svg>', s, re.S).group(0)

def clean(c):
    # Flat card for print: no shadow or rounded corners (the printer die-cuts),
    # gold frame pulled in to clear the 1/8 in safe zone, blank packer line.
    c = c.replace("background:#2b2b30;border-radius:10px;box-shadow:0 8px 22px rgba(0,0,0,.4);", "background:#2b2b30;", 1)
    c = c.replace("position:absolute;inset:10px;", "position:absolute;inset:18px;", 1)
    c = c.replace(">Sam</div>", "></div>")
    return c

front, back = clean(front), clean(back)
assert "Sam<" not in front and "inset:18px" in front and "inset:18px" in back

def page(marks):
    # Trim 2.5 x 3.5 in, 1/8 in bleed. With marks: 1/4 in white slug for crop marks.
    slug = 0.25 if marks else 0
    W, H = 2.75 + 2 * slug, 3.75 + 2 * slug
    def sheet(inner):
        crop = ""
        if marks:
            t0x, t1x = slug + 0.125, slug + 0.125 + 2.5
            t0y, t1y = slug + 0.125, slug + 0.125 + 3.5
            L = 0.2
            for x in (t0x, t1x):
                crop += f'<i style="left:{x}in;top:0;width:0;height:{L}in;border-left:.25pt solid #000"></i>'
                crop += f'<i style="left:{x}in;top:{H-L}in;width:0;height:{L}in;border-left:.25pt solid #000"></i>'
            for y in (t0y, t1y):
                crop += f'<i style="top:{y}in;left:0;height:0;width:{L}in;border-top:.25pt solid #000"></i>'
                crop += f'<i style="top:{y}in;left:{W-L}in;height:0;width:{L}in;border-top:.25pt solid #000"></i>'
        return (f'<section class="sheet">{crop}'
                f'<div class="bleed" style="left:{slug}in;top:{slug}in"></div>'
                f'<div class="card" style="left:{slug+0.125}in;top:{slug+0.125}in">{inner}</div></section>')
    return f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>TTD Thank-you Card Print{" Proof" if marks else ""}</title>
<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=JetBrains+Mono:wght@400;500&display=swap" rel="stylesheet">
<link rel="stylesheet" href="../guide.css">
<style>
  /* Generated by the print script; edit thank-you-insert-options.html instead. */
  @font-face {{ font-family: "Gotham Black"; src: url("../fonts/Gotham-Black.otf") format("opentype"); font-weight: 900; }}
  @page {{ size: {W}in {H}in; margin: 0; }}
  html, body {{ background: #fff; padding: 0; margin: 0; }}
  .sheet {{ position: relative; width: {W}in; height: {H}in; overflow: hidden; break-after: page; }}
  .sheet:last-child {{ break-after: auto; }}
  .bleed {{ position: absolute; width: 2.75in; height: 3.75in; background: #2b2b30; }}
  .card {{ position: absolute; width: 2.5in; height: 3.5in; }}
  .card > div {{ zoom: {240/312:.6f}; }}
  .sheet > i {{ position: absolute; display: block; }}
  * {{ -webkit-print-color-adjust: exact; print-color-adjust: exact; }}
</style>
</head>
<body>
{defs}
{sheet(front)}
{sheet(back)}
</body>
</html>
'''

open(f"{root}/print/thank-you-card-print.html", "w").write(page(False))
open(f"{root}/print/thank-you-card-proof.html", "w").write(page(True))
print("ok")
